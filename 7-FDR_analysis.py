def load_lda_stats():
    """读取 8 个 LDA 原始数据文件全部数据，计算 tobit 删失计数。

    返回 {(country, period): (n_total, n_uncensored_PD, n_uncensored_ND)}：
      n_total         = 表的总行数（全部观测，无遗漏）
      n_uncensored_PD = n_total - (pd==0 的观测数)
      n_uncensored_ND = n_total - (nd==0 的观测数)
    """
    stats = {}
    for country, period, path in LDA_FILES:
        df = pd.read_excel(path)                 # 读取该表的全部行与列，无遗漏
        n_total = len(df)
        n_cens_pd = int((df['pd'] == 0).sum())   # PD 左删失（取 0）观测数
        n_cens_nd = int((df['nd'] == 0).sum())   # ND 左删失（取 0）观测数
        stats[(country, period)] = (n_total, n_total - n_cens_pd, n_total - n_cens_nd)
        print(f'  LDA {country} {period}: n_total={n_total}, '
              f'n_uncensored_PD={n_total - n_cens_pd}, n_uncensored_ND={n_total - n_cens_nd}')
    return stats


