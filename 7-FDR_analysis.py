def ame_pd(country, period, beta_pd):
    n_total, n_unc_pd, _ = LDA_STATS[(country, period)]
    return round(beta_pd * n_unc_pd / n_total, 3)


def ame_nd(country, period, beta_nd):
    n_total, _, n_unc_nd = LDA_STATS[(country, period)]
    return round(beta_nd * n_unc_nd / n_total, 3)


def bh_fdr(pvals):
    """对一列 p 值单独做 BH-FDR，返回 q 值列表。"""
    _, q, _, _ = multipletests([min(p, 0.999) for p in pvals],
                               alpha=FDR_ALPHA, method='fdr_bh')
    return list(q)


def fmt_q(p_raw_str, q):
    """q 值显示：原始 p>=0.05 -> '---'；q<0.001 -> '<0.001'；否则 3 位小数。"""
    if clean_p(p_raw_str) >= 0.05:
        return '---'
    if q < 0.001:
        return '<0.001'
    return f'{q:.3f}'


def set_cell(cell, text):
    """保留原格式（Times New Roman 11pt 居中）改写单元格文本。"""
    p = cell.paragraphs[0]
    runs = p.runs
    if len(runs) == 0:
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(11)
    else:
        runs[0].text = text
        for r in runs[1:]:
            r.text = ''
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER


def strip_star(cell):
    """去掉单元格文本末尾的 '*'（用于 beta 列，清除旧的错误标记）。"""
    p = cell.paragraphs[0]
    if not p.runs:
        return
    p.runs[0].text = p.runs[0].text.replace('*', '')
    for r in p.runs[1:]:
        r.text = ''


def append_summary_section(doc):
    """若 ORIG_DOCX 缺少「Supplementary Table 17」汇总表，从模板恢复该节。

    投稿版 docx 只含补充表 9-16（tobit + Wald），缺失补充表 17（FDR 汇总表）。
    这里从模板（含排版好的标题段、100×12 汇总表、三个脚注段）深拷贝该节，
    插入到文档末尾（sectPr 之前），使汇总表重新成为第 9 张表（doc.tables[8]）。
    """
    from copy import deepcopy
    from docx.oxml.ns import qn

    if len(doc.tables) >= 9:
        return  # 已有汇总表，无需恢复

    tpl = Document(SUMMARY_TEMPLATE_DOCX)
    tpl_body = tpl.element.body

    # 定位模板中「Supplementary Table 17」标题段
    start = None
    for i, el in enumerate(tpl_body):
        if el.tag == qn('w:p'):
            texts = el.findall('.//' + qn('w:t'))
            txt = ''.join(t.text or '' for t in texts)
            if txt.strip().startswith('Supplementary Table 17'):
                start = i
                break
    if start is None:
        raise RuntimeError('模板中未找到 Supplementary Table 17 汇总表')

    # 收集标题段 → 汇总表 → 脚注段（直到 sectPr）
    elems = []
    for el in list(tpl_body)[start:]:
        if el.tag == qn('w:sectPr'):
            break
        elems.append(deepcopy(el))

    body = doc.element.body
    sectPr = body.find(qn('w:sectPr'))
    idx = body.index(sectPr)
    for k, el in enumerate(elems):
        body.insert(idx + k, el)


def main():
    n = len(TOBIT_DATA)
    assert n == len(WALD_DATA) == 98, (n, len(WALD_DATA))

    # ---- AME 计算（beta x 未删失率）----
    ame_pd_vals = [ame_pd(t[0], t[1], float(t[4])) for t in TOBIT_DATA]
    ame_nd_vals = [ame_nd(t[0], t[1], float(t[6])) for t in TOBIT_DATA]

    # ---- 三个家族分别 BH-FDR ----
    p_pd = [clean_p(t[5]) for t in TOBIT_DATA]                    # PD
    p_nd = [clean_p(t[7]) for t in TOBIT_DATA]                    # ND
    p_wald = [stats.chi2.sf(float(w[4]), 1) for w in WALD_DATA]   # Wald：chi2 -> 精确 p

    q_pd = bh_fdr(p_pd)
    q_nd = bh_fdr(p_nd)
    q_wald = bh_fdr(p_wald)

    q_pd_disp = [fmt_q(t[5], q_pd[i]) for i, t in enumerate(TOBIT_DATA)]
    q_nd_disp = [fmt_q(t[7], q_nd[i]) for i, t in enumerate(TOBIT_DATA)]
    q_wald_disp = [fmt_q(w[5], q_wald[i]) for i, w in enumerate(WALD_DATA)]

    # ---- 统计"丢失"变量（* 标记：原始 P<0.05 但 q>=0.05）----
    lost_pd = sum(1 for i in range(n) if clean_p(TOBIT_DATA[i][5]) < 0.05 and q_pd[i] >= 0.05)
    lost_nd = sum(1 for i in range(n) if clean_p(TOBIT_DATA[i][7]) < 0.05 and q_nd[i] >= 0.05)
    lost_wald = sum(1 for i in range(n) if clean_p(WALD_DATA[i][5]) < 0.05 and q_wald[i] >= 0.05)
